/// Ответ ассистента по ключевым словам (офлайн).
String getAiAssistantReply(String userMessage) {
  final lower = userMessage.toLowerCase();

  for (final entry in aiAssistantResponses.entries) {
    if (lower.contains(entry.key)) {
      final responses = entry.value;
      final index = userMessage.length % responses.length;
      return responses[index];
    }
  }

  final defaults = aiAssistantResponses['default']!;
  return defaults[DateTime.now().second % defaults.length];
}

